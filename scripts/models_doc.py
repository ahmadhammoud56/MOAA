#!/usr/bin/env python3
"""Generate MODELS.md: every MOAA agent's preset model and effort, read from the shipped sources of truth.

  python scripts/models_doc.py          write MODELS.md
  python scripts/models_doc.py --check  exit 1 if MODELS.md is out of date
"""
import importlib.util
import json
from pathlib import Path
import re
import sys

KIT = Path(__file__).resolve().parents[1]
COUNCIL = KIT / "plugins" / "specialist-council"
ARENA = KIT / "plugins" / "agent-arena-mode"
OUT = KIT / "MODELS.md"


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(path.parent))
    spec.loader.exec_module(module)
    return module


def frontmatter(path):
    block = path.read_text(encoding="utf-8").split("---")[1]
    return {k.strip(): v.strip().strip('"') for k, v in (l.split(":", 1) for l in block.splitlines() if ":" in l)}


def build():
    council = load(COUNCIL / "council.py", "council_doc")
    arena = load(ARENA / "scripts" / "arena.py", "arena_doc")
    profile = council.load_profile(COUNCIL / "profile.json")
    models = profile["models"]
    judge = frontmatter(ARENA / "agents" / "arena-judge.md")
    out = ["# Agent models and effort", "",
           "Generated by `scripts/models_doc.py` from the shipped sources of truth. Do not edit by hand.", "",
           "Every value below is stored inside the plugins themselves (agent frontmatter, `profile.json`, `arena.py`), "
           "so it applies wherever the plugins are installed: through the MOAA installer or straight from the marketplace. "
           "An explicit per-call model or effort override wins over these presets.", "",
           "## Model IDs", "", "| Tier | Model ID |", "|---|---|"]
    out += [f"| {tier} | `{models[tier]}` |" for tier in council.TIERS]
    out += ["", f"Effort levels: {', '.join(profile['effort_levels'])}. Personality effort shifts are capped at "
            f"`{profile['effort_ceiling']}` unless a role's preset is already higher.", "",
            "## Specialist Council (`specialist-council@moaa`)", "",
            "Source: `plugins/specialist-council/profile.json`, applied to each `agents/council-<role>.md` by `council.py apply`. "
            "`council.py check` fails if any agent file drifts from the profile. Agents are named `specialist-council:council-<role>`.", "",
            "| Role | Model | Effort |", "|---|---|---|"]
    for rid, role in sorted(profile["roles"].items()):
        out.append(f"| {rid} | `{models[role['tier']]}` | {role['effort']} |")
    out += ["", "Personality effort shifts: " + ", ".join(f"{s} {v:+d}" for s, v in sorted(profile["personality_effort_shift"].items())) + ".", "",
            "## Arena-forged council members", "",
            "A forged member keeps the model and effort it was validated with in the arena. Both are written into its card, "
            "`~/.claude/agents/council-forged-<slug>.md`, and into `~/.claude/specialist-council/forged/registry.json`. "
            "`council.py resolve --role forged-<slug>` returns them, and `council.py check` verifies that card and registry agree. "
            "No forged members ship with MOAA.", "",
            "## Agent Arena (`agent-arena-mode@moaa`)", "",
            f"- `agent-arena-judge` agent: `{judge['model']}`, effort {judge['effort']} (frontmatter of `agents/arena-judge.md`).",
            "- Per-run assignments come from `scripts/arena.py`, keyed by task difficulty:", "",
            "| Difficulty | Workers (tier/effort, share) | " + " | ".join(r.capitalize() for r in arena.ROLE_SETTINGS) + " |",
            "|---|---|" + "---|" * len(arena.ROLE_SETTINGS)]
    for level in arena.DIFFICULTIES:
        workers = ", ".join(f"{t}/{e} {int(s * 100)}%" for t, e, s in arena.WORKER_MIX[level])
        roles = " | ".join("/".join(arena.ROLE_SETTINGS[r][level]) for r in arena.ROLE_SETTINGS)
        out.append(f"| {level} | {workers} | {roles} |")
    out += ["", "Tier names map to the model IDs above (`arena.MODEL_IDS` must equal the council's `profile.json` models; a test enforces this)."]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("MODELS.md up to date" if ok else "MODELS.md out of date: run scripts/models_doc.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}")
