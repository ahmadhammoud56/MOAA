#!/usr/bin/env python3
"""Rebuild the upstream part of .claude-plugin/marketplace.json from this machine's installed plugins.

Every upstream plugin listed in config/kit.json is referenced (never copied) at the exact commit it is
installed at here: `github` source for plugins at a repo root, `git-subdir` for plugins in a subfolder.
Vendored MOAA plugins (relative ./plugins/... sources) are kept as they are. Standard library only.

  python scripts/sync_catalog.py            write the marketplace
  python scripts/sync_catalog.py --check    exit 1 if the marketplace is out of date
  python scripts/sync_catalog.py --drift    list pinned repos whose upstream HEAD has moved (network; no install needed)
"""
import json
import os
from pathlib import Path
import re
import sys

KIT = Path(__file__).resolve().parents[1]
MARKET = KIT / ".claude-plugin" / "marketplace.json"
SHA = re.compile(r"^[0-9a-f]{40}$")
# Names reserved for Anthropic's own plugins may not appear in a third-party marketplace; list them under an alias.
ALIASES = {"claude-api": "llm-api-reference", "claude-mem": "persistent-memory", "claude-mem-cowork": "persistent-memory-cowork"}


def claude_home():
    return Path(os.environ.get("CLAUDE_CONFIG_DIR") or Path.home() / ".claude").expanduser()


def repo_slug(url):
    match = re.match(r"(?:https://github\.com/)?([^/]+/[^/]+?)(?:\.git)?/?$", url)
    if not match:
        raise ValueError(f"not a GitHub repo: {url}")
    return match.group(1)


def upstream_entries(home, kit):
    plugins_dir = home / "plugins"
    installed = json.loads((plugins_dir / "installed_plugins.json").read_text(encoding="utf-8"))["plugins"]
    entries = []
    for item in kit["plugins"]:
        name, market = item["id"].split("@")
        if market == kit["name"]:
            continue
        catalog = json.loads((plugins_dir / "marketplaces" / market / ".claude-plugin" / "marketplace.json")
                             .read_text(encoding="utf-8"))
        upstream = next(p for p in catalog["plugins"] if p["name"] == name)
        record = installed[item["id"]][0]
        sha = record.get("gitCommitSha")
        if not (sha and SHA.match(sha)):
            raise ValueError(f"{item['id']}: no full commit SHA recorded in installed_plugins.json")
        src = upstream["source"]
        if isinstance(src, dict):  # the marketplace already points at an external repo (e.g. Anthropic's official one)
            repo = repo_slug(src.get("repo") or src["url"])
            rel = src.get("path", "")
        else:
            repo = repo_slug(kit["marketplaces"][market])
            rel = str(src).removeprefix("./").strip("/")
        source = ({"source": "github", "repo": repo, "sha": sha} if rel in ("", ".") else
                  {"source": "git-subdir", "url": f"https://github.com/{repo}.git", "path": rel, "sha": sha})
        entry = {k: v for k, v in upstream.items() if k not in ("source", "name")}
        alias = ALIASES.get(name)
        if alias:
            entry["description"] = f"{entry.get('description', '').rstrip('.')}. Upstream plugin `{name}` from {market}; listed as `{alias}` because `{name}` is a reserved name."
        entry = {"name": alias or name, "source": source, **entry}
        entry.setdefault("homepage", f"https://github.com/{repo}")
        entry["category"] = entry.get("category") or "upstream"
        entry["tags"] = sorted(set(entry.get("tags", [])) | {f"upstream:{market}"} |
                               ({"optional"} if item.get("optional") else set()))
        entries.append(entry)
    return sorted(entries, key=lambda e: e["name"])


def build(home=None):
    kit = json.loads((KIT / "config" / "kit.json").read_text(encoding="utf-8"))
    market = json.loads(MARKET.read_text(encoding="utf-8"))
    vendored = [p for p in market["plugins"] if isinstance(p["source"], str)]
    market["plugins"] = vendored + upstream_entries(home or claude_home(), kit)
    return market


README = KIT / "README.md"
START, END = "<!-- PLUGIN-LIST:START (generated by scripts/sync_catalog.py) -->", "<!-- PLUGIN-LIST:END -->"


def plugin_table(market):
    """Markdown list of every catalog plugin, grouped by where it comes from."""
    def short(text, n=110):
        text = " ".join(str(text or "").split()).replace("|", "/")
        return text if len(text) <= n else text[:n - 1].rstrip() + "…"
    own = [p for p in market["plugins"] if isinstance(p["source"], str)]
    upstream = [p for p in market["plugins"] if isinstance(p["source"], dict)]
    lines = [START, "", f"**{len(market['plugins'])} plugins**: {len(own)} MOAA plugins and {len(upstream)} "
             "third-party plugins pinned to tested commits. Install any of them with `/plugin install <name>@moaa`.", "",
             "### MOAA plugins", "", "| Install | Description |", "|---|---|"]
    lines += [f"| `{p['name']}@moaa` | {short(p.get('description'))} |" for p in own]
    groups = {}
    for p in upstream:
        src = p["source"]
        repo = src.get("repo") or src["url"].removeprefix("https://github.com/").removesuffix(".git")
        groups.setdefault(repo, []).append(p)
    lines += ["", "### Third-party plugins", ""]
    for repo, items in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0].lower())):
        sha = items[0]["source"]["sha"]
        plural = "s" if len(items) > 1 else ""
        lines += [f"<details><summary><b>{repo}</b>: {len(items)} plugin{plural} (pinned <code>{sha[:7]}</code>)</summary>",
                  "", "| Install | Description |", "|---|---|"]
        lines += [f"| `{p['name']}@moaa` | {short(p.get('description'))} |" for p in sorted(items, key=lambda e: e["name"])]
        lines += ["", f"Source: https://github.com/{repo}", "", "</details>", ""]
    lines.append(END)
    return "\n".join(lines)


def readme_with_table(market):
    text = README.read_text(encoding="utf-8")
    if START not in text:
        raise ValueError("README.md lacks the plugin-list markers")
    head, rest = text.split(START, 1)
    return head + plugin_table(market) + rest.split(END, 1)[1]


def upstream_drift(market, ls_remote=None):
    """[(repo, pinned sha, upstream HEAD sha, plugin count)] for pinned repos whose default branch has moved on.
    Needs only the network, not an install, so CI can run it. A moved HEAD in a monorepo need not touch our plugins."""
    import subprocess
    ls_remote = ls_remote or (lambda url: subprocess.run(["git", "ls-remote", url, "HEAD"], capture_output=True,
                                                         text=True, timeout=60).stdout.split("\t")[0].strip())
    repos = {}
    for p in market["plugins"]:
        src = p["source"]
        if isinstance(src, dict):
            url = f"https://github.com/{src['repo']}.git" if src.get("repo") else src["url"]
            pin, n = repos.get(url, (src["sha"], 0))
            repos[url] = (pin, n + 1)
    out = []
    for url, (pin, n) in sorted(repos.items()):
        head = ls_remote(url)
        if head and head != pin:
            out.append((url.removeprefix("https://github.com/").removesuffix(".git"), pin, head, n))
    return out


if __name__ == "__main__" and "--drift" in sys.argv:
    moved = upstream_drift(json.loads(MARKET.read_text(encoding="utf-8")))
    for repo, pin, head, n in moved:
        print(f"  {repo:<45} pinned {pin[:7]}  upstream HEAD {head[:7]}  ({n} plugin{'s' if n > 1 else ''})")
    print(f"[sync_catalog] {len(moved)} pinned repo(s) have newer commits upstream" if moved else
          "[sync_catalog] every pinned repo is at its upstream HEAD")
    print("  To adopt: update the plugins locally (`claude plugin update ...`), test, then run scripts/sync_catalog.py"
          if moved else "")
    sys.exit(0)  # informational: CI flags vendored-skill drift, not routine upstream commits

if __name__ == "__main__":
    market = build()
    text = json.dumps(market, indent=2, ensure_ascii=False) + "\n"
    readme = readme_with_table(market)
    if "--check" in sys.argv:
        ok = MARKET.read_text(encoding="utf-8") == text and README.read_text(encoding="utf-8") == readme
        print("catalog and README plugin list up to date" if ok else "out of date: run scripts/sync_catalog.py")
        sys.exit(0 if ok else 1)
    MARKET.write_text(text, encoding="utf-8", newline="\n")
    README.write_text(readme, encoding="utf-8", newline="\n")
    upstream = sum(1 for p in market["plugins"] if isinstance(p["source"], dict))
    print(f"marketplace: {len(market['plugins'])} plugins ({len(market['plugins']) - upstream} vendored, {upstream} upstream, pinned)")
